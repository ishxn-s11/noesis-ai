"""Published PARSEC v1.2S stellar evolution tracks (EEP-matched v2.0).

Data: curated subsets of https://philrosenfield.github.io/padova_tracks/
(two metallicity grids — Z = 0.014 solar and Z = 0.001 metal-poor; 29
tracks each, 0.1–100 M☉; regenerated by scripts/convert_parsec_tracks.py).
Full provenance — source release, citations (Bressan+2012, Chen+2014,
Tang+2014, Rosenfield+2016, Dotter 2016), derivation formulas and license
note — lives in the per-grid data/parsec_*_provenance.json files and is
served with every prediction via provenance().

All interpolation is local (numpy); no network access at query time.

Metallicity interpolation: between the two grid metallicities we blend in
log Z (weights linear in log Z), after aligning tracks on a common log-age
axis. Requested Z outside [0.001, 0.014] is rejected — never extrapolated.

Isochrones are derived from these tracks (fixed-age interpolation per
grid mass, ordered by mass); masses whose tracks do not span the requested
age are omitted and reported — see isochrone().

Evolution-phase identification (documented approximations):
- ZAMS point = point of maximum surface gravity along the track.
- MS end = first post-ZAMS point with L > 1.3 x L_ZAMS (luminosity proxy).
Phase ages for an interpolated Z are the log-Z-weighted blend of the
bracketing grids' phase ages.
"""
import csv
import json
import math
from functools import lru_cache
from pathlib import Path

import numpy as np

from app.core.errors import ValidationErr

DATA_DIR = Path(__file__).resolve().parent / "data"
DEFAULT_Z = 0.014  # solar grid is the default source (backward compatible)

# grid metallicity -> (tracks CSV, provenance JSON)
GRID_FILES = {
    0.014: ("parsec_solar_tracks.csv", "parsec_provenance.json"),
    0.001: ("parsec_z0.001_tracks.csv", "parsec_z0.001_provenance.json"),
}

MS_END_LUM_FACTOR = 1.3
_DOWNsample_POINTS = 90


# ---------------------------------------------------------------------------- loading

@lru_cache(maxsize=1)
def _grids() -> dict[float, dict[float, dict[str, np.ndarray]]]:
    """{z: {initial_mass: {log_age, log_teff, log_lum, log_g, radius, mass}}}."""
    out: dict[float, dict[float, dict[str, np.ndarray]]] = {}
    for z, (csv_name, _prov) in GRID_FILES.items():
        tracks: dict[float, list[dict]] = {}
        with open(DATA_DIR / csv_name, newline="") as fh:
            for row in csv.DictReader(fh):
                m = float(row["initial_mass_msun"])
                tracks.setdefault(m, []).append(row)
        grid: dict[float, dict[str, np.ndarray]] = {}
        for m, rows in tracks.items():
            rows.sort(key=lambda r: float(r["log_age_yr"]))
            grid[m] = {
                "log_age": np.array([float(r["log_age_yr"]) for r in rows]),
                "log_teff": np.array([float(r["log_teff"]) for r in rows]),
                "log_lum": np.array([float(r["log_lum"]) for r in rows]),
                "log_g": np.array([float(r["log_g"]) for r in rows]),
                "radius": np.array([float(r["radius_rsun"]) for r in rows]),
                "mass": np.array([float(r["mass_msun"]) for r in rows]),
            }
        out[z] = grid
    return out


def available_metallicities() -> list[float]:
    return sorted(_grids())


def _grid_key(z: float) -> float:
    """Exact grid metallicity matching `z` (tolerance 0.5%), else ValidationErr."""
    for gz in available_metallicities():
        if abs(math.log10(z / gz)) < 0.002:
            return gz
    raise ValidationErr(
        f"metallicity Z={z:g} outside available PARSEC grids "
        f"(Z={', '.join(f'{g:g}' for g in available_metallicities())}); "
        f"interpolation only — extrapolation in Z is not performed")


def _z_bracket(z: float) -> list[tuple[float, float]]:
    """[(grid_z, weight)] for `z`: a single grid hit, or two grids weighted in log Z."""
    zs = available_metallicities()
    tol = 1e-9
    if not (zs[0] - tol <= z <= zs[-1] + tol):
        raise ValidationErr(
            f"metallicity Z={z:g} outside available PARSEC grids "
            f"(Z={', '.join(f'{g:g}' for g in zs)}); "
            f"interpolation only — extrapolation in Z is not performed")
    lo = max([g for g in zs if g <= z], default=zs[0])
    hi = min([g for g in zs if g >= z], default=zs[-1])
    if lo == hi or abs(math.log10(z / lo)) < 1e-12:
        return [(lo, 1.0)]
    w = math.log10(z / lo) / math.log10(hi / lo)
    return [(lo, 1.0 - w), (hi, w)]


def _mass_bracket(masses: list[float], mass_msun: float) -> tuple[float, float]:
    lo = max([m for m in masses if m <= mass_msun], default=masses[0])
    hi = min([m for m in masses if m >= mass_msun], default=masses[-1])
    return lo, hi


@lru_cache(maxsize=1)
def provenance() -> dict:
    """Merged provenance: solar-grid record + per-grid metallicity information."""
    prov = json.loads((DATA_DIR / GRID_FILES[DEFAULT_Z][1]).read_text())
    grids = {}
    for z, (_csv_name, prov_name) in GRID_FILES.items():
        p = json.loads((DATA_DIR / prov_name).read_text())
        grids[str(z)] = {
            "helium_y": p.get("helium_y"),
            "n_rows": p.get("n_rows"),
            "n_tracks": len(p.get("masses_msun", [])),
            "provenance_file": prov_name,
            "downloaded_utc": p.get("downloaded_utc"),
        }
    masses = track_masses(DEFAULT_Z)
    prov["metallicities_z"] = available_metallicities()
    prov["grids"] = grids
    prov["grid"] = {
        "n_tracks": len(masses),
        "mass_range_msun": [min(masses), max(masses)],
        "interpolation": "linear in log_age within a track; linear in log mass "
                         "between bracketing tracks; linear in log Z between "
                         "bracketing metallicity grids (no extrapolation in Z)",
    }
    return prov


def track_masses(metallicity_z: float = DEFAULT_Z) -> list[float]:
    return sorted(_grids()[_grid_key(metallicity_z)].keys())


# ---------------------------------------------------------------------------- phases

def _zams_index(tr: dict[str, np.ndarray]) -> int:
    return int(np.argmax(tr["log_g"]))


def _ms_end_index(tr: dict[str, np.ndarray], zams: int) -> int:
    l_zams = tr["log_lum"][zams]
    above = np.nonzero(tr["log_lum"][zams:] > l_zams + math.log10(MS_END_LUM_FACTOR))[0]
    return int(zams + above[0]) if len(above) else len(tr["log_age"]) - 1


def _interp_track(tr: dict[str, np.ndarray], log_age: float) -> dict[str, float]:
    return {k: float(np.interp(log_age, tr["log_age"], tr[k]))
            for k in ("log_teff", "log_lum", "log_g", "radius", "mass")}


# ---------------------------------------------------------------------------- HR curves

def _blend_curves(tr_z: list[tuple[dict[str, np.ndarray], float]]) -> dict[str, np.ndarray]:
    """Blend one track per grid Z onto a common log-age axis (weights in log Z)."""
    if len(tr_z) == 1:
        return tr_z[0][0]
    tracks = [t for t, _w in tr_z]
    lo_age = max(float(t["log_age"][0]) for t in tracks)
    hi_age = min(float(t["log_age"][-1]) for t in tracks)
    if hi_age <= lo_age:
        raise ValidationErr("overlapping track ages empty across metallicity grids")
    ages = np.union1d(tracks[0]["log_age"], tracks[1]["log_age"])
    ages = ages[(ages >= lo_age) & (ages <= hi_age)]
    out: dict[str, np.ndarray] = {"log_age": ages}
    for key in ("log_teff", "log_lum", "log_g", "mass"):
        acc = np.zeros_like(ages)
        for t, w in tr_z:
            acc = acc + w * np.interp(ages, t["log_age"], t[key])
        out[key] = acc
    r_acc = np.zeros_like(ages)
    for t, w in tr_z:
        r_acc = r_acc + w * np.log10(np.interp(ages, t["log_age"], t["radius"]))
    out["radius"] = 10 ** r_acc
    return out


def _blended_track(mass_msun: float, z_pair: list[tuple[float, float]]
                    ) -> tuple[dict[str, np.ndarray], float]:
    """Full-resolution track for `mass_msun` blended across the Z bracket.

    Returns (blended_track, primary_grid_mass): each bracketing grid
    contributes its nearest-mass track, weighted in log Z.
    """
    primary = max(z_pair, key=lambda zw: zw[1])[0]
    tr_z: list[tuple[dict[str, np.ndarray], float]] = []
    grid_m = primary
    for z, w in z_pair:
        grid = _grids()[z]
        masses = sorted(grid)
        m = min(masses, key=lambda x: abs(math.log10(x / mass_msun)))
        grid_m = m if z == primary else grid_m
        tr_z.append((grid[m], w))
    return _blend_curves(tr_z), grid_m


def hr_track(mass_msun: float, metallicity_z: float = DEFAULT_Z) -> dict:
    """Downsampled HR curve for one grid mass at the requested metallicity.

    Includes ZAMS/MS-end proxy markers (computed on the full-resolution
    curve) so the track browser can show phase boundaries.
    """
    z_pair = _z_bracket(metallicity_z)
    full, grid_m = _blended_track(mass_msun, z_pair)

    zams = _zams_index(full)
    ms_end = _ms_end_index(full, zams)
    idx = np.linspace(0, len(full["log_age"]) - 1,
                      min(_DOWNsample_POINTS, len(full["log_age"]))).astype(int)
    z_note = "" if metallicity_z == DEFAULT_Z else f", Z={metallicity_z:g}"
    return {
        "grid_mass_msun": grid_m,
        "metallicity_z": metallicity_z,
        "label": f"PARSEC {grid_m:g} M☉{z_note}",
        "log_teff": full["log_teff"][idx].tolist(),
        "log_lum": full["log_lum"][idx].tolist(),
        "zams": {"log_teff": float(full["log_teff"][zams]),
                 "log_lum": float(full["log_lum"][zams])},
        "ms_end": {"log_teff": float(full["log_teff"][ms_end]),
                   "log_lum": float(full["log_lum"][ms_end])},
    }


def track_browser(metallicity_z: float = DEFAULT_Z) -> dict:
    """All full-grid evolutionary paths for the track-browser view."""
    z_pair = _z_bracket(metallicity_z)
    primary = max(z_pair, key=lambda zw: zw[1])[0]
    masses = track_masses(primary)
    return {
        "metallicity_z": metallicity_z,
        "metallicities_z": available_metallicities(),
        "n_tracks": len(masses),
        "tracks": [hr_track(m, metallicity_z) for m in masses],
        "provenance": provenance(),
    }


# ---------------------------------------------------------------------------- isochrones

@lru_cache(maxsize=128)
def isochrone(age_yr: float, metallicity_z: float = DEFAULT_Z) -> dict:
    """Fixed-age isochrone derived from the EEP-matched track grid.

    For the requested age, every grid track whose stored age range spans the
    age is linearly interpolated at that age (in log age); the resulting
    points are ordered by initial mass. Masses whose tracks do not span the
    age are OMITTED and reported in `excluded_masses_msun` — massive stars
    simply have shorter stored tracks, so an old isochrone legitimately
    ends at a low mass. Nothing is ever extrapolated or silently dropped.
    """
    age = float(age_yr)
    if not math.isfinite(age) or age <= 0:
        raise ValidationErr(f"age_yr must be positive and finite (got {age_yr!r})")
    log_age = math.log10(age)
    z_pair = _z_bracket(metallicity_z)
    primary = max(z_pair, key=lambda zw: zw[1])[0]
    masses = track_masses(primary)

    points: list[dict] = []
    excluded: list[float] = []
    for m in masses:
        full, _grid_m = _blended_track(m, z_pair)
        start, end = float(full["log_age"][0]), float(full["log_age"][-1])
        if log_age < start or log_age > end:
            excluded.append(m)
            continue
        pt = _interp_track(full, log_age)
        points.append({"mass_msun": m, "log_teff": pt["log_teff"],
                       "log_lum": pt["log_lum"]})
    if not points:
        raise ValidationErr(
            f"age {age:.3g} yr is outside the track grid's coverage at "
            f"Z={metallicity_z:g} (no grid track spans this age)")
    return {
        "age_yr": age,
        "metallicity_z": metallicity_z,
        "derivation": "isochrone computed from the stored EEP-matched tracks: each "
                      "grid track interpolated at the fixed age (linear in log age), "
                      "points ordered by initial mass; masses whose tracks do not "
                      "span this age are omitted and listed in excluded_masses_msun "
                      "(never extrapolated)",
        "n_points": len(points),
        "n_tracks_total": len(masses),
        "excluded_masses_msun": excluded,
        "points": points,
        "provenance": provenance(),
    }


# ---------------------------------------------------------------------------- point model

def point_parameters(mass_msun: float, age_yr: float | None = None,
                     metallicity_z: float = DEFAULT_Z) -> dict:
    """Interpolated stellar parameters at (mass, age, Z) from published tracks.

    Defaults to the mid-main-sequence age (between the ZAMS proxy and the
    luminosity-based MS-end proxy). The returned dict mirrors the analytic
    model's keys so the UI can swap sources transparently, and carries
    `provenance` + `track` for transparency and plotting.
    """
    z_pair = _z_bracket(metallicity_z)

    # Phase bookkeeping per bracketing grid Z (on that grid's bracketing low track)
    info: dict[float, dict] = {}
    for z, _w in z_pair:
        grid = _grids()[z]
        masses = sorted(grid)
        if not (min(masses) <= mass_msun <= max(masses)):
            raise ValidationErr(
                f"PARSEC grid at Z={z:g} covers {min(masses):g}–{max(masses):g} M☉ "
                f"(requested {mass_msun:g}); use source='analytic' outside the grid")
        lo, hi = _mass_bracket(masses, mass_msun)
        tr = grid[lo]
        zams, ms_end = _zams_index(tr), _ms_end_index(tr, _zams_index(tr))
        info[z] = {
            "lo": lo, "hi": hi,
            "zams_log_age": float(tr["log_age"][zams]),
            "ms_end_log_age": float(tr["log_age"][ms_end]),
            "start_log_age": float(tr["log_age"][0]),
            "end_log_age": float(tr["log_age"][-1]),
        }

    def blend(vals: dict[float, float]) -> float:
        if len(z_pair) == 1:
            return vals[z_pair[0][0]]
        return sum(w * vals[z] for z, w in z_pair)

    zams_log = blend({z: i["zams_log_age"] for z, i in info.items()})
    ms_end_log = blend({z: i["ms_end_log_age"] for z, i in info.items()})
    start_log = blend({z: i["start_log_age"] for z, i in info.items()})
    end_log = blend({z: i["end_log_age"] for z, i in info.items()})

    clamped = None
    if age_yr is None:
        log_age = (zams_log + ms_end_log) / 2  # geometric mid-MS
        age_use = 10 ** log_age
        age_note = "defaulted to mid-MS age (geometric mean of ZAMS and MS-end)"
    else:
        age_use = float(age_yr)
        age_note = "caller-supplied age"
        log_age = math.log10(age_use)
        if log_age < start_log or log_age > end_log:
            clamped = (f"age {age_use:.3g} yr outside stored track range "
                       f"[{10 ** start_log:.3g}, {10 ** end_log:.3g}] yr; clamped")
            log_age = float(np.clip(log_age, start_log, end_log))
            age_use = 10 ** log_age

    # Evaluate and blend the stellar point across the Z bracket.
    # Log quantities and log radius are linear in the log-Z weight.
    accs = {k: 0.0 for k in ("log_teff", "log_lum", "log_g", "mass")}
    log_r = 0.0
    for z, w in z_pair:
        grid, i = _grids()[z], info[z]
        if i["hi"] == i["lo"]:
            pt = _interp_track(grid[i["lo"]], log_age)
        else:
            a = _interp_track(grid[i["lo"]], log_age)
            b = _interp_track(grid[i["hi"]], log_age)
            wm = (math.log10(mass_msun) - math.log10(i["lo"])) \
                / (math.log10(i["hi"]) - math.log10(i["lo"]))
            pt = {k: a[k] * (1 - wm) + b[k] * wm for k in a}
        for k in accs:
            accs[k] += w * pt[k]
        log_r += w * math.log10(pt["radius"])

    radii = 10 ** log_r
    teff = 10 ** accs["log_teff"]
    from app.physics.stellar.main_sequence import spectral_class

    cls, sub, cls_note = spectral_class(teff)
    primary = max(z_pair, key=lambda zw: zw[1])[0]
    ip = info[primary]
    masses_desc = (f"bracketing tracks {ip['lo']:g}–{ip['hi']:g} M☉"
                   if ip["hi"] != ip["lo"] else f"grid track {ip['lo']:g} M☉")
    z_word = "Solar metallicity" if metallicity_z == DEFAULT_Z else "Metallicity"

    assumptions = [
        f"{z_word} Z={metallicity_z:g} ({masses_desc})",
        "ZAMS = max surface gravity; MS end = first L > 1.3 L_ZAMS (proxy)",
        "Linear interpolation in log age within a track, in log mass between tracks",
    ]
    if len(z_pair) > 1:
        zs_desc = " and ".join(f"Z={z:g}" for z, _w in z_pair)
        assumptions.append(
            f"Linear interpolation in log Z between the {zs_desc} grids "
            f"(no extrapolation in Z); phase ages blended in log age")
    assumptions.append(
        "TP-AGB points included in stored tracks; no stellar-wind mass-loss "
        "model beyond PARSEC's")
    if clamped:
        assumptions.append(f"WARNING: {clamped}")

    return {
        "model_fidelity": f"PUBLISHED TRACK (PARSEC v1.2S, locally interpolated, "
                          f"Z={metallicity_z:g})",
        "assumptions": assumptions,
        "mass_msun": mass_msun,
        "age_yr": age_use,
        "age_note": age_note,
        "metallicity_z": metallicity_z,
        "teff_K": teff,
        "luminosity_msun": 10 ** accs["log_lum"],
        "radius_msun": radii,
        "surface_log_g": accs["log_g"],
        "current_mass_msun": accs["mass"],
        "spectral_class": f"{cls}{sub}",
        "classification_note": cls_note,
        "zams_age_yr": 10 ** zams_log,
        "ms_end_age_yr_proxy": 10 ** ms_end_log,
        "track_end_age_yr": 10 ** end_log,
        "ms_lifetime_yr_proxy": 10 ** ms_end_log - 10 ** zams_log,
        "ms_lifetime_Gyr_proxy": (10 ** ms_end_log - 10 ** zams_log) / 1e9,
        "age_clamped": clamped,
        "provenance": provenance(),
        "track": hr_track(mass_msun, metallicity_z),
        "references": [c for c in provenance()["citations"]],
    }